const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const root = path.resolve(__dirname,"..");
const publicDir = path.join(root,"public");
const required = new Set();
function walk(dir) { return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]); }
for (const file of walk(path.join(root,"src"))) {
  if (!/\.(tsx?|css|json)$/.test(file)) continue;
  const text = fs.readFileSync(file,"utf8");
  for (const match of text.matchAll(/\/workshop\/[A-Za-z0-9_./-]+\.(?:webp|png|svg|jpg|jpeg|avif|gif)/g)) required.add(match[0]);
}
// These URLs are deliberately assembled at runtime; enumerate their typed item
// registries rather than relying on a stale hand-maintained file list.
const exportsMotion = {};
new Function("exports",ts.transpileModule(fs.readFileSync(path.join(root,"src/lib/workshop/mobile-motion.ts"),"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(exportsMotion);
for(const id of Object.keys(exportsMotion.mobileLampItems)) for(const suffix of ["lamp-v1","lamp-plate-v1"]) required.add(`/workshop/mobile-${id}-${suffix}.webp`);
for(const id of Object.keys(exportsMotion.mobileCatItems)) {
  required.add(`/workshop/mobile-${id}-cat-v1.webp`);
  required.add(`/workshop/mobile-${id}-cat-plate-${id==="contact"?"v2":"v1"}.webp`);
}
for(const url of required) if(!fs.existsSync(path.join(publicDir,url))) throw new Error(`Missing runtime asset: ${url}`);
const ordinary = walk(publicDir).filter(f=>!f.startsWith(path.join(publicDir,"workshop")+path.sep) && !path.basename(f).startsWith("__") && !path.relative(publicDir,f).split(path.sep).some(part=>part.startsWith(".")));
const files = [...required].map(url=>path.join(publicDir,url)).concat(ordinary).sort();
const sourceBytes = walk(publicDir).reduce((n,f)=>n+fs.statSync(f).size,0);
const bytes = files.reduce((n,f)=>n+fs.statSync(f).size,0);
if(!process.argv.includes("--check")) {
  const out = path.join(root,".production/public");
  const marker = path.join(root,".production/.owned-public");
  if(fs.existsSync(out)) {
    if(!fs.existsSync(marker)) throw new Error("Refusing to replace an unmarked output directory");
    fs.rmSync(out,{recursive:true});
  }
  fs.mkdirSync(out,{recursive:true});
  for(const file of files) {const destination=path.join(out,path.relative(publicDir,file));fs.mkdirSync(path.dirname(destination),{recursive:true});fs.copyFileSync(file,destination);}
  fs.writeFileSync(marker,"Generated by scripts/prepare-production-public.cjs\n");
  fs.mkdirSync(path.join(root,".production"),{recursive:true});
  fs.writeFileSync(path.join(root,".production/public-manifest.json"),JSON.stringify({files:files.map(f=>path.relative(publicDir,f)),bytes,sourceBytes},null,2)+"\n");
}
console.log(JSON.stringify({files:files.length,bytes,sourceBytes,savedBytes:sourceBytes-bytes,mode:process.argv.includes("--check")?"check":"package"}));
